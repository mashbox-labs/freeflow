import AppKit
import ApplicationServices
import Carbon

/// Puts the finished text into the app you are in, at the cursor: the text goes on the clipboard, Free Flow presses
/// Command-V for you, and then your own clipboard is put back as it was (unless something else copied in the
/// meantime). The text is marked transient so clipboard managers skip it. Pressing keys in another app needs
/// Accessibility; without it the text stays on the clipboard and the pill says so.
enum TextInserter {
    enum Result: Equatable { case pasted, copied }

    /// How long the app in front gets to read the clipboard before yours comes back.
    static let restoreAfter: UInt64 = 900_000_000

    @MainActor
    static func insert(_ text: String) async -> Result {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ours = pb.changeCount
        guard AXIsProcessTrusted() else { return .copied }
        pressPaste()
        try? await Task.sleep(nanoseconds: restoreAfter)
        if pb.changeCount == ours { restore(saved, to: pb) }
        return .pasted
    }

    /// Every item on the clipboard with every type it offers, as data.
    static func snapshot(_ pb: NSPasteboard) -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pb.pasteboardItems ?? []).map { item in item.types.compactMap { t in item.data(forType: t).map { (t, $0) } } }
    }

    static func restore(_ saved: [[(NSPasteboard.PasteboardType, Data)]], to pb: NSPasteboard) {
        pb.clearContents()
        let items = saved.filter { !$0.isEmpty }.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }

    static func pressPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = keyCode(for: "v") ?? 9   // kVK_ANSI_V
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
    }

    /// The key that types `character` with Command held, in the keyboard layout shortcuts use (the current
    /// ASCII-capable one): Command-V is not key 9 on Dvorak, and "Dvorak - QWERTY Command" switches back under Command.
    static func keyCode(for character: String) -> CGKeyCode? {
        guard let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
        return data.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            let command = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<128 {
                var dead: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), command, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysMask), &dead, 4, &length, &chars)
                if status == noErr, length == 1, String(utf16CodeUnits: chars, count: 1).lowercased() == character {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}
